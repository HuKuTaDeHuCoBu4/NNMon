    function Show-FinalScreen {
        param([string]$subtitle)
        Clear-Host
        Write-Host "==============================" -ForegroundColor Cyan
        if ($subtitle) {
            Write-Host "   $subtitle" -ForegroundColor Yellow
        }
        Write-Host "==============================" -ForegroundColor Cyan
        Write-Host ""
        Read-Host "Нажмите Enter для возврата в меню"
        Set-Variable -Name state -Value "end" -Scope 1
    }

    # Вспомогательная функция для безопасного выбора (защита от пустого ввода)
    function Get-Choice {
        param(
            [string[]]$ValidOptions,
            [string]$Prompt = "Ваш выбор"
        )
        while ($true) {
            $choice = Read-Host $Prompt
            if ($choice -in $ValidOptions) {
                return $choice
            }
            Write-Host "Пожалуйста, введите один из вариантов: $($ValidOptions -join ', ')" -ForegroundColor Yellow
        }
    }

